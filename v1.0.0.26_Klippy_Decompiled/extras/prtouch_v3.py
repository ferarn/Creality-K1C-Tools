from . import prtouch_v3_wrapper
from . import probe

class PrtouchProbe:

    def __init__(self, config):
        self.printer = config.get_printer()
        self.mcu_probe = prtouch_v3_wrapper.PRTouchEndstopWrapper(config)
        self.cmd_helper = probe.ProbeCommandHelper(config, self, self.mcu_probe.query_endstop)
        self.probe_offsets = probe.ProbeOffsetsHelper(config)
        self.probe_session = probe.ProbeSessionHelper(config, self.mcu_probe)

    def get_probe_params(self, gcmd=None):
        return self.probe_session.get_probe_params(gcmd)

    def get_offsets(self):
        return self.probe_offsets.get_offsets()

    def get_status(self, eventtime):
        return self.cmd_helper.get_status(eventtime)

    def start_probe_session(self, gcmd):
        return self.probe_session.start_probe_session(gcmd)

    def get_lift_speed(self, gcmd):
        return self.probe_session.lift_speed

    def get_probe_speed(self, gcmd):
        if gcmd is not None:
            return gcmd.get_float("PROBE_SPEED", (self.probe_session.speed), above=0.0)
        return self.probe_session.speed


def load_config(config):
    prtouch = PrtouchProbe(config)
    config.get_printer().add_object("probe", prtouch)
    return prtouch

