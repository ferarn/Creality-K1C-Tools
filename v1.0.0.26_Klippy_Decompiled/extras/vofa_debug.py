import socket, math
from configfile import *
from gcode import *

class VOFADebug:

    def __init__(self, config: ConfigWrapper=None):
        self.printer = config.get_printer()
        self.gcode = self.printer.lookup_object("gcode")
        self.dbg_ippt = config.get("dbg_ippt", default="172.25.10.198")
        self.dbg_port = config.getint("dbg_port", 21023)
        self.show_msg = config.getboolean("show_msg", default=False)
        self.gcode.register_command("VOFA_DEBUG", (self.cmd_VOFA_DEBUG), desc=(self.cmd_VOFA_DEBUG_help))

    cmd_VOFA_DEBUG_help = "VOFA Debug Command Test Show a sin waveform on the host computer."

    def cmd_VOFA_DEBUG(self, gcmd: GCodeCommand):
        num_points = gcmd.get_int("NUM_POINTS", 100)
        frequency = gcmd.get_float("FREQUENCY", 1.0)
        amplitude = gcmd.get_float("AMPLITUDE", 1.0)
        phase = gcmd.get_float("PHASE", 0.0)
        sin_data = [amplitude * math.sin(2 * math.pi * frequency * t / num_points + phase) for t in range(num_points)]
        for i in sin_data:
            self.print_data_vofashow(title="Sin Waveform", msg=[i])

    def print_data_vofashow(self, title=None, msg=None, force=False):
        if self.dbg_ippt is None:
            return
        if not self.show_msg:
            return
        data_str = ""
        for i in msg:
            data_str += "{:.3f},".format(i)

        send_str = "data:" + data_str[:-1] + "\n"
        if title is not None:
            self.gcode.respond_info(("[" + title + "]" + send_str), log=False)
        self.socket_send_data(send_str, self.dbg_port)

    def socket_send_data(self, send_str, dbg_port=21023):
        if self.dbg_ippt is None:
            return
        if not self.show_msg:
            return
        ss = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        ss.sendto(str(send_str).encode(), (str(self.dbg_ippt), dbg_port))
        ss.close()


g_VOFADebug = None

