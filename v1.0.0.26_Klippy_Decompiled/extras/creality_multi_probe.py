class PrinterMultiProbe:

    def __init__(self, config):
        self.printer = config.get_printer()
        self.stepper_rail = None
        self.run_probe = None
        self.scan_probe_name = config.get("scan_probe")
        self.scan_probe = None
        self.probe_list = []
        self.probe_list_name = config.getlist("probes")
        for probe_name in self.probe_list_name:
            probe = self.printer.load_object(config, probe_name)
            if self.printer.lookup_object("probe") is not None:
                self.printer.delete_object("probe")
            self.probe_list.append((probe, probe_name))
            if probe_name == self.scan_probe_name:
                self.scan_probe = (
                 probe, probe_name)

        if self.scan_probe is None:
            raise config.error("Config object '%s' not exist" % self.scan_probe_name)
        self.gcode = self.printer.lookup_object("gcode")
        self.printer.register_event_handler("klippy:mcu_identify", self._handle_mcu_identify)
        self.printer.register_event_handler("klippy:ready", self._handle_ready)

    def _handle_mcu_identify(self):
        kin = self.printer.lookup_object("toolhead").get_kinematics()
        self.stepper_rail = kin.rails[2]

    def _handle_ready(self):
        self.set_run_probe(self.probe_list_name[0])

    def get_probelist(self):
        return self.probe_list

    def get_main_probe(self):
        return self.probe_list[0][0]

    def get_main_mcu_probe(self):
        return self.probe_list[0][0].mcu_probe

    def get_main_probe_name(self):
        return self.probe_list[0][1]

    def get_scan_probe(self):
        return self.scan_probe[0]

    def get_scan_mcu_probe(self):
        return self.scan_probe[0].mcu_probe

    def get_scan_probe_name(self):
        return self.scan_probe[1]

    def get_run_probe(self):
        return self.run_probe

    def get_run_mcu_probe(self):
        return self.run_probe.mcu_probe

    def set_run_probe(self, name):
        for probe in self.probe_list[:]:
            if probe[1] == name:
                self.printer.delete_object("probe")
                self.run_probe = probe[0]
                self.printer.add_object("probe", self.run_probe)
                self.stepper_rail.update_endstop(self.run_probe.mcu_probe, "z")

    def start_auto_probe(self, current_probe, auto_probe, cmd):
        if auto_probe not in self.probe_list_name:
            raise self.printer.command_error("Config object '%s' must be specified" % auto_probe)
        if current_probe not in self.probe_list_name:
            raise self.printer.command_error("Config object '%s' must be specified" % current_probe)
        self.set_run_probe(auto_probe)
        self.gcode.run_script_from_command(cmd)
        self.gcode.run_script_from_command("BED_MESH_CLEAR")
        self.gcode.run_script_from_command("G1 Z0")
        self.set_run_probe(current_probe)
        toolhead = self.printer.lookup_object("toolhead")
        toolhead.flush_step_generation()
        kin = toolhead.get_kinematics()
        kin_spos = {s.get_name(): s.get_commanded_position() for s in kin.get_steppers()}
        kin_pos = kin.calc_position(kin_spos)
        return kin_pos

    def probe(self, cmd):
        self.gcode.run_script_from_command(cmd)
        self.gcode.run_script_from_command("BED_MESH_CLEAR")
        self.gcode.run_script_from_command("G1 Z0")
        toolhead = self.printer.lookup_object("toolhead")
        toolhead.flush_step_generation()
        kin = toolhead.get_kinematics()
        kin_spos = {s.get_name(): s.get_commanded_position() for s in kin.get_steppers()}
        kin_pos = kin.calc_position(kin_spos)
        return kin_pos


def load_config(config):
    return PrinterMultiProbe(config)

