class CutModule:

    def __init__(self, config: "ConfigWrapper"):
        self.config = config
        self.printer = config.get_printer()
        self.printer.register_event_handler("klippy:ready", self._find_objs)
        self.status = None

    def _find_objs(self):
        self.box = self.printer.lookup_object("box")
        self.status = self.box.box_state

    def get_status(self, eventime):
        if self.status is None:
            return {}
        return {'state':(self.status).cutter_state, 
         'cutter_sensor':(self.status).cutter_sensor, 
         'buffer_state':(self.status).buffer_state, 
         'cut_success_count':(self.status).cut_success_count, 
         'tip_count':(self.status).tip_count}


def load_config(config):
    return CutModule(config)

