import logging
KELVIN_TO_CELSIUS = -273.15

class PrinterSensorGeneric:

    def __init__(self, config):
        self.printer = config.get_printer()
        self.reactor = self.printer.get_reactor()
        self.name = config.get_name().split()[-1]
        pheaters = self.printer.load_object(config, "heaters")
        self.gcode = self.printer.lookup_object("gcode")
        self.sensor = pheaters.setup_sensor(config)
        self.min_temp = config.getfloat("min_temp", KELVIN_TO_CELSIUS, minval=KELVIN_TO_CELSIUS)
        self.max_temp = config.getfloat("max_temp", 99999999.9, above=(self.min_temp))
        self.sensor.setup_minmax(-9999999999999.0, 9999999999999.0)
        self.sensor.setup_callback(self.temperature_callback)
        pheaters.register_sensor(config, self)
        self.last_temp = 0.0
        self.measured_min = 99999999.0
        self.measured_max = 0.0
        self.error_repeat = False

    def temperature_callback(self, read_time, temp):
        if temp < self.min_temp or temp > self.max_temp:
            if not self.error_repeat:
                self.error_repeat = True
                msg = "Sensor %s temperature %.1f out of range" % (self.name, temp)
                logging.error(msg)
                self.reactor.register_async_callback(lambda e: self.gcode.respond_error(msg), self.reactor.monotonic() + 5.0)
        else:
            self.error_repeat = False
            self.last_temp = temp
            if temp:
                self.measured_min = min(self.measured_min, temp)
                self.measured_max = max(self.measured_max, temp)

    def get_temp(self, eventtime):
        return (
         self.last_temp, 0.0)

    def stats(self, eventtime):
        return (
         False, "%s: temp=%.1f" % (self.name, self.last_temp))

    def get_status(self, eventtime):
        return {'temperature':round(self.last_temp, 2), 
         'measured_min_temp':round(self.measured_min, 2), 
         'measured_max_temp':round(self.measured_max, 2)}


def load_config_prefix(config):
    return PrinterSensorGeneric(config)

