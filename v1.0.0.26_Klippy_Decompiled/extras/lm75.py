        self.report_time = config.getfloat("lm75_report_time", LM75_REPORT_TIME, minval=LM75_MIN_REPORT_TIME)
        self.temp = self.min_temp = self.max_temp = 0.0
        self.sample_timer = self.reactor.register_timer(self._sample_lm75)
