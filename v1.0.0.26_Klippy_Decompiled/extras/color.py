import math

def color_distance(color1: int, color2: int):
    r1 = color1 >> 16 & 255
    g1 = color1 >> 8 & 255
    b1 = color1 & 255
    r2 = color2 >> 16 & 255
    g2 = color2 >> 8 & 255
    b2 = color2 & 255
    deltaR = (r1 - r2) * 0.3
    deltaG = (g1 - g2) * 0.59
    deltaB = (b1 - b2) * 0.11
    return math.sqrt(deltaR * deltaR + deltaG * deltaG + deltaB * deltaB)

